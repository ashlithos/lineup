// Bundles the MCP Apps widget into one self-contained HTML string.
//
// Chat hosts render widgets in a sandboxed iframe whose CSP blocks CDN
// scripts, so the App SDK and our code are inlined. The output is a TS
// module (committed) so app/mcp/route.ts can import it without touching the
// filesystem at runtime. Runs automatically before `next build`.
//
//   npm run build:widget

import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const bundle = await build({
  entryPoints: [path.join(root, "mcp/widget/app.ts")],
  bundle: true,
  format: "iife",
  minify: true,
  target: "es2020",
  platform: "browser",
  write: false,
  alias: { "@": root },
  legalComments: "none",
});

const js = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const template = await readFile(path.join(root, "mcp/widget/app.html"), "utf8");
const html = template.replace("<!-- SCRIPT -->", () => `<script>${js}</script>`);

await writeFile(
  path.join(root, "lib/mcp/widget-html.generated.ts"),
  `// Generated by scripts/build-mcp-widget.mjs from mcp/widget/. Don't edit.\n` +
    `export const WIDGET_HTML = ${JSON.stringify(html)};\n`,
);

console.log(`mcp widget: ${(html.length / 1024).toFixed(1)} KB`);
